"""OvmfPkg platform adapter (Interface I2).

The adapter translates between the Config Model and EDK II platform
files. Two directions: ``generate`` (config -> DSC/FDF + build command)
and ``import`` (DSC/FDF -> config).

Workspace
---------
The adapter needs the EDK II workspace path (the tree checkout) to read
the stock DSC/FDF and to derive the PCD set. The design's I2 signature
``generate(config)`` carries no workspace parameter, so the workspace is
adapter configuration: the caller (the GUI, after loading settings, or a
test fixture) calls ``set_workspace(path)`` once before ``generate`` or
``get_pcd_names``. Both raise ``RuntimeError`` with a clear message when
the workspace is not configured.

Generation
----------
``generate`` writes a thin-wrapper DSC into ``<workspace>/Generated/``:
it ``!include``s the stock ``OvmfPkg/OvmfPkgX64.dsc``, sets
``FLASH_DEFINITION`` to the generated FDF path (after the include, so it
overrides the stock value), and sets the configured PCD values in a
``[PcdsFixedAtBuild]`` section (overriding the stock values). The
generated FDF is a copy of the stock ``OvmfPkg/OvmfPkgX64.fdf`` (v1 does
not change the flash layout). Generation never overwrites a stock file.
``generate`` assumes a validated config (the GUI validates before
calling it); it does not re-validate.

PCD set
-------
``get_pcd_names`` derives the offered PCD set at runtime from the
installed EDK II tree — there is no hard-coded PCD list. It parses the
PCD sections (``[PcdsFixedAtBuild]``, ``[PcdsDynamicDefault]``,
``[PcdsPatchableInModule]``) of the stock DSC and every file its
``!include`` chain resolves to, plus the ``.dec`` files of the packages
the DSC chain references (a package is a ``*Pkg`` path component in an
include path or a library path). Unresolvable includes are skipped.

Import
------
``import`` (added in design step 5) uses a bounded hand-written parser
for the constructs in OvmfPkg's DSC/FDF. The design's first choice was
EDK II BaseTools (``Workspace/DscBuildData.py`` for DSC, ``GenFds/`` for
FDF), with the hand-written parser as the fallback "if BaseTools' API
proves unsuitable at implementation". On the implementation machine used
here there is no EDK II tree at all, so BaseTools cannot even be
imported or evaluated; the bounded parser is the implementation, per
that fallback clause. It covers sections, PCD assignments, ``!include``
of the stock files (unresolvable includes become warnings), and library
class overrides (warnings). Anything that does not map to the schema
goes to the warnings list, never silently dropped.
"""

from __future__ import annotations

import re
import shutil
from pathlib import Path

PLATFORM = "OvmfPkg"
SUPPORTED_ARCHITECTURES = {"X64"}
SUPPORTED_BUILD_TARGETS = {"DEBUG", "RELEASE", "NOOPT"}
SUPPORTED_TOOLCHAINS = {"GCC5"}

STOCK_DSC_REL = Path("OvmfPkg") / "OvmfPkgX64.dsc"
STOCK_FDF_REL = Path("OvmfPkg") / "OvmfPkgX64.fdf"
GENERATED_DIRNAME = "Generated"
GENERATED_DSC_NAME = "OvmfPkgX64.dsc"
GENERATED_FDF_NAME = "OvmfPkgX64.fdf"

PCD_SECTIONS = ("PcdsFixedAtBuild", "PcdsDynamicDefault", "PcdsPatchableInModule")

_SECTION_RE = re.compile(r"^\s*\[([A-Za-z0-9_.]+)\]")
_PCD_LINE_RE = re.compile(r"^\s*([A-Za-z0-9_]+)\.([A-Za-z0-9_]+)\s*\|\s*(.*?)\s*$")
_INCLUDE_RE = re.compile(r"^\s*!include\s+(\S+)")
_PACKAGE_RE = re.compile(r"([A-Za-z0-9_]+Pkg)/")

_workspace: Path | None = None


def set_workspace(path) -> None:
    """Point the adapter at an EDK II workspace (or None to clear it)."""
    global _workspace
    _workspace = Path(path) if path is not None else None


def get_workspace() -> Path | None:
    """Return the configured workspace, or None if not configured."""
    return _workspace


def _require_workspace() -> Path:
    if _workspace is None:
        raise RuntimeError(
            "OvmfPkg adapter workspace is not configured; call set_workspace() "
            "with the EDK II workspace path first."
        )
    return _workspace


def generate(config):
    """Generate DSC/FDF from a config.

    Returns ``(dsc_path, fdf_path, build_command, image_path)``. The
    build command is an argument list (not a shell string); the image
    path is absolute.
    """
    workspace = _require_workspace()
    stock_dsc = workspace / STOCK_DSC_REL
    stock_fdf = workspace / STOCK_FDF_REL
    if not stock_dsc.is_file():
        raise FileNotFoundError(f"Stock OvmfPkg DSC not found: {stock_dsc}")
    if not stock_fdf.is_file():
        raise FileNotFoundError(f"Stock OvmfPkg FDF not found: {stock_fdf}")

    generated_dir = workspace / GENERATED_DIRNAME
    generated_dir.mkdir(parents=True, exist_ok=True)
    dsc_path = generated_dir / GENERATED_DSC_NAME
    fdf_path = generated_dir / GENERATED_FDF_NAME

    lines = [
        "## @file",
        "# Generated by bios-build-gui from the build configuration. Do not edit",
        "# by hand; edit the configuration in the GUI and rebuild.",
        "#",
        "",
        "!include OvmfPkg/OvmfPkgX64.dsc",
        "",
        "[Defines]",
        f"  FLASH_DEFINITION = {GENERATED_DIRNAME}/{GENERATED_FDF_NAME}",
        "",
        "[PcdsFixedAtBuild]",
    ]
    for name in sorted(config.pcds):
        lines.append(f"  {name}|{config.pcds[name]}")
    dsc_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    # The generated FDF is a copy of the stock FDF: v1 does not change
    # the flash layout.
    shutil.copyfile(stock_fdf, fdf_path)

    command = [
        "build",
        "-p",
        f"{GENERATED_DIRNAME}/{GENERATED_DSC_NAME}",
        "-a",
        config.architecture,
        "-t",
        config.toolchain,
        "-b",
        config.build_target,
    ]
    image_path = (
        workspace
        / "Build"
        / "OvmfX64"
        / f"{config.build_target}_{config.toolchain}"
        / "FV"
        / "OVMF.fd"
    )
    return dsc_path, fdf_path, command, image_path


def get_pcd_names() -> set[str]:
    """Derive the offered PCD set from the installed EDK II tree."""
    workspace = _require_workspace()
    dsc_path = workspace / STOCK_DSC_REL
    if not dsc_path.is_file():
        raise FileNotFoundError(f"Stock OvmfPkg DSC not found: {dsc_path}")
    names: set[str] = set()
    for path in _collect_dsc_chain(dsc_path, workspace):
        for section, section_lines in _iter_sections(
            path.read_text(encoding="utf-8", errors="replace")
        ):
            if section in PCD_SECTIONS:
                names.update(name for name, _value in _pcd_entries(section_lines))
    for package in _referenced_packages(dsc_path, workspace):
        package_dir = workspace / package
        if not package_dir.is_dir():
            continue
        for dec_path in sorted(package_dir.glob("*.dec")):
            for section, section_lines in _iter_sections(
                dec_path.read_text(encoding="utf-8", errors="replace")
            ):
                if section in PCD_SECTIONS:
                    names.update(name for name, _value in _pcd_entries(section_lines))
    return names


def _iter_sections(text):
    """Yield ``(section_name, lines)`` for each section in a DSC/FDF/DEC file.

    Section headers may carry an arch qualifier (``[PcdsFixedAtBuild.X64]``);
    the qualifier is stripped. Full-line ``#`` comments and blank lines are
    dropped. Lines before the first section are yielded under ``None``.
    ``!`` directives (``!include``, ``!if``/``!endif``) are kept as lines.
    """
    current = None
    buf: list[str] = []
    for raw in text.splitlines():
        line = raw.strip()
        match = _SECTION_RE.match(line)
        if match:
            yield current, buf
            current = match.group(1).split(".")[0]
            buf = []
            continue
        if not line or line.startswith("#"):
            continue
        buf.append(line)
    yield current, buf


def _pcd_entries(lines):
    """Extract ``(TokenSpaceGuidCName.PcdName, value)`` pairs from section lines.

    Lines starting with ``!`` (``!if``/``!endif`` and friends) are skipped;
    PCD lines inside a conditional block are still collected (the
    condition is a build-time flag the parser does not evaluate).
    """
    entries = []
    for line in lines:
        if line.startswith("!"):
            continue
        match = _PCD_LINE_RE.match(line)
        if match:
            entries.append((f"{match.group(1)}.{match.group(2)}", match.group(3)))
    return entries


def _resolve_include(include_target, including_file, workspace):
    """Resolve an ``!include`` target to a file, or None if unresolvable.

    EDK II resolves includes relative to the workspace; fall back to the
    including file's directory.
    """
    candidate = workspace / include_target
    if candidate.is_file():
        return candidate
    candidate = including_file.parent / include_target
    if candidate.is_file():
        return candidate
    return None


def _collect_dsc_chain(dsc_path, workspace, _depth=0, _seen=None):
    """Return the DSC file plus every file its ``!include`` chain resolves to.

    Cycles are guarded by the seen set; depth is bounded at 10.
    Unresolvable includes are skipped (the caller that needs them — the
    importer — records them as warnings instead).
    """
    if _seen is None:
        _seen = set()
    resolved = dsc_path.resolve()
    if resolved in _seen or _depth > 10:
        return []
    _seen.add(resolved)
    files = [dsc_path]
    try:
        text = dsc_path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return files
    for raw in text.splitlines():
        match = _INCLUDE_RE.match(raw.strip())
        if not match:
            continue
        target = _resolve_include(match.group(1), dsc_path, workspace)
        if target is not None:
            files.extend(_collect_dsc_chain(target, workspace, _depth + 1, _seen))
    return files


def _referenced_packages(dsc_path, workspace):
    """Return the package names (``*Pkg``) referenced by the DSC chain."""
    packages = set()
    for path in _collect_dsc_chain(dsc_path, workspace):
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for match in _PACKAGE_RE.finditer(text):
            packages.add(match.group(1))
    return packages
